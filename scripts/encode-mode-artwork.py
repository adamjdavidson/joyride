#!/usr/bin/env python3
"""Encode the supplied mode PNGs as flash-backed LVGL 9 RGB565 images.

Preserves the native 256px image dimensions. The display palette tints the source
shading in indigo navy and composites transparency onto white. Original PNGs stay
unchanged. No runtime PNG decoder or full-image RAM buffer.
"""
import hashlib
import json
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / 'firmware/mode-display'
MODES = ('Download', 'Expand', 'Challenge', 'Structure', 'Implement')
INK = (41, 33, 99)  # #292163: rich navy with a slight purple cast.
PAPER = (255, 255, 255)


def encode(image):
    image = image.convert('RGBA')
    if image.size != (256, 256):
        raise ValueError('Mode artwork must be the native 256 × 256 version')
    result = bytearray()
    for r, g, b, a in image.getdata():
        # Preserve sculpted highlights/shadows while applying the display ink.
        luminance = (54 * r + 183 * g + 19 * b) / 256
        shade = (luminance / 220) ** 2
        tinted = [min(255, round(channel * shade)) for channel in INK]
        r, g, b = ((color * a + paper * (255 - a) + 127) // 255
                   for color, paper in zip(tinted, PAPER))
        value = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
        result.extend((value & 255, value >> 8))
    return result


def main():
    lines = ['// Generated by scripts/encode-mode-artwork.py; do not hand-edit.',
             '#pragma once', '#include "lvgl.h"', '#include <string.h>',
             'static constexpr uint32_t MODE_INK = 0x292163;',
             'static constexpr uint32_t MODE_PAPER = 0xFFFFFF;', '']
    manifest = {'size': [256, 256], 'format': 'RGB565 little-endian, navy shading on white',
                'ink': '#292163', 'paper': '#FFFFFF', 'images': {}}
    for name in MODES:
        slug = name.lower()
        path = DEST / 'assets' / f'{slug}.png'
        with Image.open(path) as image:
            data = encode(image)
        lines.append(f'alignas(4) static const uint8_t mode_{slug}_pixels[] = {{')
        for start in range(0, len(data), 24):
            lines.append('  ' + ','.join(f'0x{x:02x}' for x in data[start:start + 24]) + ',')
        lines.extend(['};', f'static const lv_image_dsc_t mode_{slug}_image = {{',
                      '  {LV_IMAGE_HEADER_MAGIC, LV_COLOR_FORMAT_RGB565, 0, 256, 256, 512, 0},',
                      f'  sizeof(mode_{slug}_pixels), mode_{slug}_pixels, nullptr, nullptr', '};', ''])
        manifest['images'][name] = {'source': f'assets/{slug}.png',
                                    'source_sha256': hashlib.sha256(path.read_bytes()).hexdigest(),
                                    'rgb565_sha256': hashlib.sha256(data).hexdigest(),
                                    'bytes': len(data)}
    lines.append('static const lv_image_dsc_t *modeArtwork(const char *name) {')
    for name in MODES:
        lines.append(f'  if (!strcmp(name, "{name}")) return &mode_{name.lower()}_image;')
    lines.extend(['  return nullptr;', '}', ''])
    (DEST / 'mode_artwork.h').write_text('\n'.join(lines))
    (DEST / 'assets/manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
    print(f'Encoded {len(MODES)} native 256px images: {len(MODES) * 256 * 256 * 2:,} flash bytes')


if __name__ == '__main__':
    main()
